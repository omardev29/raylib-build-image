"""Regenerate python/requirements-ci.txt from python/requirements-ci.in.

Run it INSIDE this image (any build of it: what matters is CPython 3.12 on
Linux, the interpreter the lock is installed into), from the repository root:

    docker run --rm -v "$PWD":/w -w /w ghcr.io/omardev29/raylib-build:latest sh -c '
        apt-get update -qq && apt-get install -y -qq python3-venv >/dev/null &&
        python3 -m venv /tmp/v && /tmp/v/bin/pip install -q pip-tools==7.6.2 &&
        /tmp/v/bin/python python/lock.py'

Two steps:

1. pip-compile resolves the whole graph and pins every package with ==.
2. For each pin, it asks PyPI for that release's files and keeps every wheel
   that pip could pick for CPython 3.12 on glibc 2.39 (the image's) on EITHER
   architecture the image is built for, x86_64 and aarch64. It DOWNLOADS each
   one and hashes the bytes here, and refuses if that hash differs from the
   digest PyPI publishes, or if a pinned release has no wheel for one of the
   two architectures (the Dockerfile installs with --only-binary=:all:).

Why not `pip-compile --generate-hashes`: it hashes every file of a release,
Windows and macOS wheels and the sdist included, which turns a 20-package lock
into hundreds of lines nobody can review, and it takes the hashes from PyPI's
index instead of computing them.
"""

import hashlib
import json
import pathlib
import re
import subprocess
import sys
import urllib.request

from packaging import tags
from packaging.utils import parse_wheel_filename

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "requirements-ci.in"
LOCK = HERE / "requirements-ci.txt"

PYTHON = (3, 12)
GLIBC_MINOR = 39  # noble's glibc 2.39: manylinux_2_39 down to manylinux2014
ARCHES = ("x86_64", "aarch64")

HEADER = """\
# GENERATED by python/lock.py from python/requirements-ci.in -- do not edit.
#
# Every package is pinned with ==, and every hash is of a wheel that pip can
# pick for CPython 3.12 on manylinux x86_64 or aarch64, downloaded and hashed
# by lock.py and checked against PyPI's published digest. The Dockerfile
# installs this file with --require-hashes --only-binary=:all:, so a package
# missing from it, a version that moved or a file whose bytes changed is a
# failed image build, not a different image.
"""


def supported_tags(arch):
    platforms = [f"manylinux_2_{m}_{arch}" for m in range(GLIBC_MINOR, 16, -1)]
    platforms.append(f"manylinux2014_{arch}")
    found = set(tags.cpython_tags(python_version=PYTHON, abis=["cp312"], platforms=platforms))
    found |= set(tags.compatible_tags(python_version=PYTHON, interpreter="cp312", platforms=platforms))
    return found


def compile_pins():
    result = subprocess.run(
        [sys.executable, "-m", "piptools", "compile", "--quiet", "--strip-extras",
         "--no-header", "--output-file=-", str(SOURCE.relative_to(pathlib.Path.cwd()))],
        check=True, capture_output=True, text=True)
    return result.stdout.splitlines()


def wheel_hashes(name, version, supported):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as response:
        release = json.load(response)
    hashes = set()
    per_arch = dict.fromkeys(ARCHES, 0)
    for entry in release["urls"]:
        filename = entry["filename"]
        if not filename.endswith(".whl"):
            continue
        _, _, _, wheel_tags = parse_wheel_filename(filename)
        arches = [arch for arch in ARCHES if wheel_tags & supported[arch]]
        if not arches:
            continue
        with urllib.request.urlopen(entry["url"]) as response:
            mine = hashlib.sha256(response.read()).hexdigest()
        if mine != entry["digests"]["sha256"]:
            sys.exit(f"FAIL: {filename}: the bytes hash to {mine}, "
                     f"PyPI publishes {entry['digests']['sha256']}")
        for arch in arches:
            per_arch[arch] += 1
        hashes.add(mine)
        print(f"  {filename}", file=sys.stderr)
    for arch, count in per_arch.items():
        if count == 0:
            sys.exit(f"FAIL: {name}=={version} publishes no wheel for CPython 3.12 "
                     f"manylinux {arch}, and the image installs with --only-binary=:all:")
    return sorted(hashes)


def main():
    supported = {arch: supported_tags(arch) for arch in ARCHES}
    out = [HEADER]
    for line in compile_pins():
        pin = re.match(r"^([A-Za-z0-9_.-]+)==(\S+)$", line)
        if not pin:
            out.append(line.replace(str(SOURCE.relative_to(pathlib.Path.cwd())), "requirements-ci.in"))
            continue
        name, version = pin.groups()
        print(f"{name}=={version}", file=sys.stderr)
        hashes = wheel_hashes(name, version, supported)
        out.append(f"{line} \\")
        out.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                   for i, h in enumerate(hashes))
    LOCK.write_text("\n".join(out) + "\n")
    print(f"wrote {LOCK.relative_to(pathlib.Path.cwd())}", file=sys.stderr)


if __name__ == "__main__":
    main()
